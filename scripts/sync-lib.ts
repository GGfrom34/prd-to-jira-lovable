// Pure helpers for copying sections out of the Claude Code agent and skill files.
// Only text is copied here; the web-specific adaptation lives in prompts.ts.

export function normalise(text: string): string {
  return text.replace(/\r\n/g, "\n");
}

export function extractSection(markdown: string, headingPrefix: string): string {
  const lines = normalise(markdown).split("\n");
  const start = lines.findIndex((l) => l.startsWith("## ") && l.slice(3).trim().startsWith(headingPrefix));
  if (start === -1) {
    throw new Error(`Section not found: "${headingPrefix}"`);
  }
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i++) {
    if (lines[i].startsWith("## ")) {
      end = i;
      break;
    }
  }
  return lines.slice(start, end).join("\n").trim();
}

export const SOURCE_SECTIONS = [
  { name: "reviewerRubric", file: ".claude/agents/prd-quality-reviewer.md", heading: "The rubric" },
  { name: "reviewerOutputFormat", file: ".claude/agents/prd-quality-reviewer.md", heading: "Output format" },
  { name: "improverLoop", file: ".claude/skills/improve-prd/SKILL.md", heading: "How to work through it" },
  { name: "improverExample", file: ".claude/skills/improve-prd/SKILL.md", heading: "Worked example" },
  { name: "splitterBreakdown", file: ".claude/agents/jira-epic-builder.md", heading: "Step 3: Propose the breakdown" },
] as const;

export type SectionName = (typeof SOURCE_SECTIONS)[number]["name"];

export function buildSections(readSource: (relativePath: string) => string): Record<SectionName, string> {
  const out = {} as Record<SectionName, string>;
  for (const s of SOURCE_SECTIONS) {
    out[s.name] = extractSection(readSource(s.file), s.heading);
  }
  return out;
}

export function toTemplateLiteral(text: string): string {
  const escaped = text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return "`" + escaped + "`";
}

export function renderGenerated(sections: Record<SectionName, string>): string {
  const header = [
    "// GENERATED by scripts/sync-prompts.ts from the Claude Code agent and skill files.",
    "// Do not edit by hand: run `npm run sync-prompts` instead.",
    "",
  ];
  const body = SOURCE_SECTIONS.map((s) => `export const ${s.name} = ${toTemplateLiteral(sections[s.name])};`);
  return header.concat(body).join("\n") + "\n";
}
